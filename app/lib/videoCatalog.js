function buildModeEntry(model, mode, config) {
  const meta = familyMeta[model.family] || VIDEO_FAMILIES[0];
  const resolutions = config.resolutions || [];
  const durations = config.durations || [];
  return {
    id: `${model.id}-${mode}`,
    label: model.name,
    name: model.name,
    version: model.version,
    family: model.family,
    provider: meta.provider,
    logo: meta.logo,
    icon: meta.icon,
    color: meta.color,
    badge: model.badge || null,
    speed: model.speed || "Standard",
    desc: model.desc,
    supportedModes: Object.keys(model.modes),
    model_id: config.modelId,
    mode,
    requiresImage: config.requiresImage ?? mode === "image",
    requiresPrompt: config.requiresPrompt ?? mode === "text",
    requiresLastFrame: !!config.requiresLastFrame,
    supportsLastFrame: !!config.supportsLastFrame,
    lastFrameField: config.lastFrameField || null,
    imageField: config.imageField || "image_url",
    nativeAspectRatio: !!config.nativeAspectRatio,
    sizeMap: config.sizeMap || null,
    payload: config.payload || "generic",
    resolutionKey: config.resolutionKey || null,
    resolutionMap: config.resolutionMap || null,
    resolutionDurations: config.resolutionDurations || null,
    audioMode: config.audioMode || AUDIO_SILENT,
    audioMultiplier: config.audioMultiplier || 1,
    audioField: config.audioField || null,
    options: {
      aspect_ratio: config.aspectRatios || [],
      resolution: resolutions,
      duration: durations,
    },
    pricing: {
      perSecond: config.perSecond || 0,
      byResolution: config.pricingByResolution || null,
      resolutionMultipliers: config.resolutionMultipliers || null,
      audioMultiplier: config.audioMultiplier || 1,
    },
    maxResolution: maxResolution(resolutions),
    durationLabel: durationRange(durations),
    modeConfig: config,
  };
}

export const textVideoModels = VIDEO_CATALOG.flatMap((model) =>
  model.modes.text ? [buildModeEntry(model, "text", model.modes.text)] : []
);

export const videoModels = VIDEO_CATALOG.flatMap((model) =>
  model.modes.image ? [buildModeEntry(model, "image", model.modes.image)] : []
);

export const VIDEO_MODELS_BY_MODE = {
  text: textVideoModels,
  image: videoModels,
};

export function getVideoModels(mode) {
  return mode === "text" ? textVideoModels : videoModels;
}

export function getVideoModel(mode, modelId) {
  const list = getVideoModels(mode);
  return list.find((m) => m.model_id === modelId) || null;
}

export function getVideoModelById(id) {
  return [...textVideoModels, ...videoModels].find((m) => m.id === id) || null;
}

export function getPerSecondRate(model, resolution) {
  const pricing = model?.pricing || {};
  const key = normalizeResolution(resolution);
  if (pricing.byResolution) {
    return (
      pricing.byResolution[key] ??
      pricing.byResolution[normalizeResolution(model.options?.resolution?.[0])] ??
      pricing.perSecond
    );
  }
  const multiplier = pricing.resolutionMultipliers?.[key] ?? 1;
  return (pricing.perSecond || 0) * multiplier;
}

export function estimateProviderCost(model, { duration, resolution, audio } = {}) {
  const seconds = parseInt(String(duration || ""), 10) || 5;
  const rate = getPerSecondRate(model, resolution);
  const useAudio =
    audio !== false &&
    model?.audioMode !== AUDIO_SILENT &&
    model?.audioMode !== undefined;
  const audioMultiplier = useAudio ? model?.audioMultiplier || 1 : 1;
  return rate * seconds * audioMultiplier;
}

export function estimateCredits(model, settings, options = {}) {
  const usdValue = settings?.credit_usd_value || 0.01;
  const minCredits = settings?.minimum_generation_credits || 1;
  const cost = estimateProviderCost(model, options);
  const markup = resolveMarkup(cost, settings);
  const rawCredits = (cost * markup) / usdValue;
  const roundedCredits = Math.round(rawCredits * 1e6) / 1e6;
  return Math.max(Math.ceil(roundedCredits), minCredits);
}

